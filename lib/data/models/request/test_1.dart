class Autogenerated {
  List<Schedules>? schedules;

  Autogenerated({this.schedules});

  Autogenerated.fromJson(Map<String, dynamic> json) {
    if (json['schedules'] != null) {
      schedules = <Schedules>[];
      json['schedules'].forEach((v) {
        schedules!.add(new Schedules.fromJson(v));
      });
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = new Map<String, dynamic>();
    if (this.schedules != null) {
      data['schedules'] = this.schedules!.map((v) => v.toJson()).toList();
    }
    return data;
  }
}

class Schedules {
  String? id;
  List<MedicalData>? medicalData;

  Schedules({this.id, this.medicalData});

  Schedules.fromJson(Map<String, dynamic> json) {
    id = json['id'];
    if (json['medicalData'] != null) {
      medicalData = <MedicalData>[];
      json['medicalData'].forEach((v) {
        medicalData!.add(new MedicalData.fromJson(v));
      });
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = new Map<String, dynamic>();
    data['id'] = this.id;
    if (this.medicalData != null) {
      data['medicalData'] = this.medicalData!.map((v) => v.toJson()).toList();
    }
    return data;
  }
}

class MedicalData {
  String? day;
  String? reservationType;
  DayData? dayData;

  MedicalData({this.day, this.reservationType, this.dayData});

  MedicalData.fromJson(Map<String, dynamic> json) {
    day = json['day'];
    reservationType = json['reservation_type'];
    dayData =
        json['dayData'] != null ? new DayData.fromJson(json['dayData']) : null;
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = new Map<String, dynamic>();
    data['day'] = this.day;
    data['reservation_type'] = this.reservationType;
    if (this.dayData != null) {
      data['dayData'] = this.dayData!.toJson();
    }
    return data;
  }
}

class DayData {
  String? startTime;
  String? endTime;
  String? breakStartTime;
  String? breakEndTime;

  DayData(
      {this.startTime, this.endTime, this.breakStartTime, this.breakEndTime});

  DayData.fromJson(Map<String, dynamic> json) {
    startTime = json['start_time'];
    endTime = json['end_time'];
    breakStartTime = json['break_start_time'];
    breakEndTime = json['break_end_time'];
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = new Map<String, dynamic>();
    data['start_time'] = this.startTime;
    data['end_time'] = this.endTime;
    data['break_start_time'] = this.breakStartTime;
    data['break_end_time'] = this.breakEndTime;
    return data;
  }
}
